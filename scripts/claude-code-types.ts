#!/usr/bin/env bun

// Writes types/claude-code.d.ts, the plugin API declarations the mod is
// type-checked against, from a Claude Code binary.
//
// Claude Code has no command that prints them. It writes them beside the
// bundled plugin-authoring skill each time that skill loads, so the script
// loads the skill with no credentials, in an empty config and temp folder:
// the engine writes the file, then stops at "Not logged in" before any
// model call. The output depends only on the Claude Code version.
//
// Usage: bun scripts/claude-code-types.ts [--check] [--claude <path>]
// --check exits 1 when the committed file differs from what the binary
// writes. --claude defaults to the `claude` on PATH.
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseArgs } from "node:util";

const ROOT = join(import.meta.dir, "..");

export const TYPES_PATH = "types/claude-code.d.ts";

/**
 * The first line of the committed file. The declarations are generated, so
 * the fleet's lint rules do not apply to them.
 */
export const LINT_HEADER =
  "/* oxlint-disable -- Generated by Claude Code. Regenerate with bun scripts/claude-code-types.ts. */";

const GENERATED_FILE = "plugin-authoring/types/claude-code.d.ts";

const VERSION_LINE = /^\/\/ Written by Claude Code (\d+\.\d+\.\d+)\.$/m;

/** The Claude Code version named in the declarations' own header. */
export function versionOf(declarations: string): string | null {
  return VERSION_LINE.exec(declarations)?.[1] ?? null;
}

/** The `CLAUDE_CODE_VERSION` a workflow pins, or null when it pins none. */
export function pinnedVersion(workflow: string): string | null {
  return (
    /^\s*CLAUDE_CODE_VERSION:\s*"?([\d.]+)"?\s*$/m.exec(workflow)?.[1] ?? null
  );
}

/** Prepends the lint header to the engine's output. */
export function withLintHeader(declarations: string): string {
  return `${LINT_HEADER}\n${declarations}`;
}

async function run(
  command: string[],
  options: { cwd?: string; env?: Record<string, string>; stdin?: string },
): Promise<{ exitCode: number; stdout: string; stderr: string }> {
  const child = Bun.spawn(command, {
    cwd: options.cwd ?? ROOT,
    env: options.env ?? { ...process.env },
    stdin: options.stdin === undefined ? "ignore" : new Blob([options.stdin]),
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr, exitCode] = await Promise.all([
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
    child.exited,
  ]);

  return { exitCode, stdout, stderr };
}

/**
 * Loads the plugin-authoring skill in a throwaway session and returns the
 * declarations the engine wrote for it.
 */
async function generate(claude: string): Promise<string> {
  const scratch = await mkdtemp(join(tmpdir(), "claude-code-types-"));

  try {
    // Only what the binary needs to start: no API key, no OAuth token and no
    // config of the person's, so the session cannot log in or spend.
    const env: Record<string, string> = {
      PATH: process.env["PATH"] ?? "",
      HOME: scratch,
      CLAUDE_CONFIG_DIR: join(scratch, "config"),
      CLAUDE_CODE_TMPDIR: join(scratch, "tmp"),
      DISABLE_TELEMETRY: "1",
      CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: "1",
    };
    const session = await run([claude, "-p", "/plugin-authoring"], {
      cwd: scratch,
      env,
    });
    const written = await Array.fromAsync(
      new Bun.Glob(`**/${GENERATED_FILE}`).scan({
        cwd: join(scratch, "tmp"),
        dot: true,
      }),
    );

    if (written.length !== 1) {
      throw new Error(
        `Expected Claude Code to write one ${GENERATED_FILE}, found ${written.length}. ` +
          `Its output: ${(session.stdout + session.stderr).trim() || "(none)"}`,
      );
    }

    return await Bun.file(join(scratch, "tmp", written[0] ?? "")).text();
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}

/** Formats the declarations the way the committed file is formatted. */
async function format(source: string): Promise<string> {
  const oxfmt = join(ROOT, "node_modules", ".bin", "oxfmt");
  const result = await run([oxfmt, `--stdin-filepath=${TYPES_PATH}`], {
    stdin: source,
  });

  if (result.exitCode !== 0) {
    throw new Error(`oxfmt failed: ${result.stderr.trim()}`);
  }

  return result.stdout;
}

export async function main(argv: string[]): Promise<number> {
  const { values } = parseArgs({
    args: argv,
    options: {
      check: { type: "boolean", default: false },
      claude: { type: "string", default: "claude" },
    },
  });
  const expected = await format(withLintHeader(await generate(values.claude)));
  const target = join(ROOT, TYPES_PATH);
  const version = versionOf(expected) ?? "an unknown version";

  if (!values.check) {
    await Bun.write(target, expected);
    console.log(`wrote ${TYPES_PATH} from Claude Code ${version}`);

    return 0;
  }

  const file = Bun.file(target);
  const current = (await file.exists()) ? await file.text() : null;

  if (current === expected) {
    console.log(`${TYPES_PATH} matches Claude Code ${version}`);

    return 0;
  }

  console.error(
    `${TYPES_PATH} differs from what Claude Code ${version} writes. ` +
      `Fix: bun scripts/claude-code-types.ts --claude <that binary>, then commit the file.`,
  );

  return 1;
}

if (import.meta.main) {
  process.exit(await main(process.argv.slice(2)));
}
